import random
import time


# -----------------------------
# Sorting Algorithms
# -----------------------------

def bubble_sort(arr):
    arr = arr.copy()

    n = len(arr)

    for i in range(n):
        swapped = False

        for j in range(0, n - i - 1):
            if arr[j] > arr[j + 1]:
                arr[j], arr[j + 1] = arr[j + 1], arr[j]
                swapped = True

        if not swapped:
            break

    return arr


def insertion_sort(arr):
    arr = arr.copy()

    for i in range(1, len(arr)):
        key = arr[i]
        j = i - 1

        while j >= 0 and arr[j] > key:
            arr[j + 1] = arr[j]
            j -= 1

        arr[j + 1] = key

    return arr


def merge_sort(arr):
    if len(arr) <= 1:
        return arr.copy()

    mid = len(arr) // 2

    left = merge_sort(arr[:mid])
    right = merge_sort(arr[mid:])

    return merge(left, right)


def merge(left, right):
    result = []

    i = 0
    j = 0

    while i < len(left) and j < len(right):

        if left[i] <= right[j]:
            result.append(left[i])
            i += 1

        else:
            result.append(right[j])
            j += 1

    result.extend(left[i:])
    result.extend(right[j:])

    return result


def quick_sort(arr):
    if len(arr) <= 1:
        return arr.copy()

    pivot = arr[len(arr) // 2]

    left = [x for x in arr if x < pivot]
    middle = [x for x in arr if x == pivot]
    right = [x for x in arr if x > pivot]

    return quick_sort(left) + middle + quick_sort(right)


# -----------------------------
# Experiment Runner
# -----------------------------

ALGORITHMS = {
    "Bubble Sort": bubble_sort,
    "Insertion Sort": insertion_sort,
    "Merge Sort": merge_sort,
    "Quick Sort": quick_sort
}


def generate_dataset(size):
    return [random.randint(1, 100000) for _ in range(size)]


def measure_algorithm(algorithm, data):

    start_time = time.perf_counter()

    algorithm(data)

    end_time = time.perf_counter()

    return end_time - start_time


def run_sorting_experiment(dataset_sizes, runs=3):
    results = []

    for size in dataset_sizes:

        # Store measurements for each algorithm
        algorithm_times = {
            name: []
            for name in ALGORITHMS
        }

        for _ in range(runs):

            # Generate ONE dataset for this run
            data = generate_dataset(size)

            # Test every algorithm on the SAME dataset
            for name, algorithm in ALGORITHMS.items():

                execution_time = measure_algorithm(
                    algorithm,
                    data
                )

                algorithm_times[name].append(
                    execution_time
                )

        # Calculate average time for each algorithm
        for name in ALGORITHMS:

            average_time = (
                sum(algorithm_times[name])
                / len(algorithm_times[name])
            )

            results.append({
                "algorithm": name,
                "dataset_size": size,
                "average_time": average_time
            })

    return results

def calculate_verified_facts(results):
    """
    Calculate factual observations directly from measured results.
    These facts are generated by Python and can be safely provided
    to the AI analysis system.
    """

    verified_facts = {
        "dataset_sizes": [],
        "fastest_by_dataset": [],
        "slowest_by_dataset": [],
        "algorithm_trends": []
    }

    # Get unique dataset sizes from actual measurements
    dataset_sizes = sorted(
        set(item["dataset_size"] for item in results)
    )

    verified_facts["dataset_sizes"] = dataset_sizes

    # -----------------------------------
    # Fastest and slowest per dataset
    # -----------------------------------

    for size in dataset_sizes:

        measurements = [
            item
            for item in results
            if item["dataset_size"] == size
        ]

        if not measurements:
            continue

        fastest = min(
            measurements,
            key=lambda item: item["average_time"]
        )

        slowest = max(
            measurements,
            key=lambda item: item["average_time"]
        )

        verified_facts["fastest_by_dataset"].append({
            "dataset_size": size,
            "algorithm": fastest["algorithm"],
            "average_time": round(
                fastest["average_time"],
                6
            )
        })

        verified_facts["slowest_by_dataset"].append({
            "dataset_size": size,
            "algorithm": slowest["algorithm"],
            "average_time": round(
                slowest["average_time"],
                6
            )
        })

    # -----------------------------------
    # Trend for each algorithm
    # -----------------------------------

    algorithms = sorted(
        set(item["algorithm"] for item in results)
    )

    for algorithm in algorithms:

        algorithm_results = sorted(
            [
                item
                for item in results
                if item["algorithm"] == algorithm
            ],
            key=lambda item: item["dataset_size"]
        )

        if len(algorithm_results) < 2:
            continue

        times = [
            item["average_time"]
            for item in algorithm_results
        ]

        first_time = times[0]
        last_time = times[-1]

        if last_time > first_time:
            overall_direction = "increased"
        elif last_time < first_time:
            overall_direction = "decreased"
        else:
            overall_direction = "unchanged"

        # Check whether the values consistently increase/decrease
        increasing = all(
            times[i] >= times[i - 1]
            for i in range(1, len(times))
        )

        decreasing = all(
            times[i] <= times[i - 1]
            for i in range(1, len(times))
        )

        if increasing:
            pattern = "consistently increased"
        elif decreasing:
            pattern = "consistently decreased"
        else:
            pattern = "mixed"

        verified_facts["algorithm_trends"].append({
            "algorithm": algorithm,
            "first_dataset_size": algorithm_results[0]["dataset_size"],
            "first_average_time": round(first_time, 6),
            "last_dataset_size": algorithm_results[-1]["dataset_size"],
            "last_average_time": round(last_time, 6),
            "overall_direction": overall_direction,
            "pattern": pattern
        })

    return verified_facts
