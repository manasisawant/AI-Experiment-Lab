import { useEffect, useState } from "react";
import { useNavigate } from "react-router-dom";
import jsPDF from "jspdf";

function Reports() {
  const navigate = useNavigate();

  const [history, setHistory] = useState([]);

  useEffect(() => {
    const savedHistory = JSON.parse(
      localStorage.getItem("experimentHistory") || "[]"
    );

    setHistory(savedHistory);
  }, []);

  const openResults = (experiment) => {
    localStorage.setItem(
      "experimentResults",
      JSON.stringify(experiment)
    );

    navigate("/results");
  };

  const formatDate = (dateString) => {
    if (!dateString) {
      return "Unknown date";
    }
    return new Date(dateString).toLocaleString();
  };

  const downloadReport = (experiment) => {
  const pdf = new jsPDF();

  let y = 20;

  const addText = (text, x = 20, size = 11) => {
    pdf.setFontSize(size);

    const lines = pdf.splitTextToSize(
      String(text || ""),
      170
    );

    pdf.text(lines, x, y);

    y += lines.length * 6 + 4;

    // Start a new page if needed
    if (y > 275) {
      pdf.addPage();
      y = 20;
    }
  };

  // --------------------------------
  // TITLE
  // --------------------------------

  pdf.setFontSize(20);
  pdf.text("AI EXPERIMENT LAB", 20, y);

  y += 10;

  pdf.setFontSize(15);
  pdf.text("Experiment Report", 20, y);

  y += 12;

  // --------------------------------
  // BASIC INFORMATION
  // --------------------------------

  addText("EXPERIMENT", 20, 10);
  addText(experiment.experiment, 20, 12);

  addText("RESEARCH QUESTION", 20, 10);
  addText(
    experiment.question || "No research question provided.",
    20,
    11
  );

  addText("DATASET SIZES", 20, 10);
  addText(
    experiment.datasetSizes?.join(", ") || "Not available",
    20,
    11
  );

  addText("NUMBER OF RUNS", 20, 10);
  addText(experiment.runs || "Not available", 20, 11);

  addText("CREATED", 20, 10);
  addText(formatDate(experiment.createdAt), 20, 11);

  // --------------------------------
  // MEASUREMENTS
  // --------------------------------

  addText("MEASUREMENTS", 20, 13);

  if (experiment.results?.length) {
    experiment.results.forEach((result) => {
      addText(
        `${result.algorithm} | Dataset: ${result.dataset_size} | Average Time: ${(
          result.average_time * 1000
        ).toFixed(3)} ms`,
        20,
        10
      );
    });
  } else {
    addText("No measurements available.", 20, 10);
  }

  // --------------------------------
  // VERIFIED FACTS
  // --------------------------------

  if (experiment.verifiedFacts) {
    addText("VERIFIED FACTS", 20, 13);

    const facts = experiment.verifiedFacts;

    if (facts.fastest_by_dataset?.length) {
      addText("Fastest Algorithm by Dataset", 20, 11);

      facts.fastest_by_dataset.forEach((item) => {
        addText(
          `${item.dataset_size}: ${item.algorithm} (${item.average_time} seconds)`,
          20,
          10
        );
      });
    }

    if (facts.slowest_by_dataset?.length) {
      addText("Slowest Algorithm by Dataset", 20, 11);

      facts.slowest_by_dataset.forEach((item) => {
        addText(
          `${item.dataset_size}: ${item.algorithm} (${item.average_time} seconds)`,
          20,
          10
        );
      });
    }

    if (facts.algorithm_trends?.length) {
      addText("Algorithm Trends", 20, 11);

      facts.algorithm_trends.forEach((item) => {
        addText(
          `${item.algorithm}: ${item.overall_direction}; ${item.pattern}`,
          20,
          10
        );
      });
    }
  }

  // --------------------------------
  // AI ANALYSIS
  // --------------------------------

  if (experiment.aiAnalysis) {
    addText("AI ANALYSIS", 20, 13);

    addText(
      experiment.aiAnalysis,
      20,
      10
    );
  }

  // --------------------------------
  // FOOTER
  // --------------------------------

  pdf.setFontSize(8);
  pdf.text(
    "Generated by AI Experiment Lab",
    20,
    290
  );

  const filename =
    `${experiment.experiment || "experiment"}-report.pdf`
      .toLowerCase()
      .replace(/\s+/g, "-");

  pdf.save(filename);
};

  return (
    <div className="page">

      {/* ================= HEADER ================= */}

      <div className="page-header">

        <div>
          <p className="page-kicker">
            EXPERIMENT HISTORY
          </p>

          <h1>Reports</h1>

          <p>
            View and revisit experiments you have previously run.
          </p>
        </div>

      </div>


      {/* ================= EMPTY STATE ================= */}

      {history.length === 0 ? (

        <div className="empty-state">

          <div className="empty-icon">
            📄
          </div>

          <h2>
            No experiments yet
          </h2>

          <p>
            Complete an experiment and it will appear here.
          </p>

        </div>

      ) : (

        <div className="reports-list">

          {history.map((experiment) => (

            <div
              className="experiment-card report-card"
              key={experiment.id}
            >

              {/* TOP */}

              <div className="report-card-header">

                <div>

                  <p className="page-kicker">
                    EXPERIMENT
                  </p>

                  <h2>
                    {experiment.experiment}
                  </h2>

                </div>

                <span className="report-date">
                  {formatDate(experiment.createdAt)}
                </span>

              </div>


              {/* QUESTION */}

              <div className="report-question">

                <span>
                  RESEARCH QUESTION
                </span>

                <p>
                  {experiment.question ||
                    "No research question provided."}
                </p>

              </div>


              {/* DETAILS */}

              <div className="report-details">

                <div>
                  <span>
                    DATASET SIZES
                  </span>

                  <strong>
                    {experiment.datasetSizes?.join(", ")}
                  </strong>
                </div>


                <div>
                  <span>
                    RUNS
                  </span>

                  <strong>
                    {experiment.runs}
                  </strong>
                </div>


                <div>
                  <span>
                    MEASUREMENTS
                  </span>

                  <strong>
                    {experiment.results?.length || 0}
                  </strong>
                </div>

              </div>


              {/* BUTTON */}

             <div className="report-actions">

  <button
    className="run-button report-view-button"
    onClick={() => openResults(experiment)}
  >
    View Results →
  </button>

  <button
    className="download-report-button"
    onClick={() => downloadReport(experiment)}
  >
    ↓ Download PDF
  </button>

</div> 

            </div>

          ))}

        </div>

      )}

    </div>
  );
}

export default Reports;